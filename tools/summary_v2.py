"""🧪 prototype: summary ที่เก็บ "เนื้อหา" ไม่ใช่แค่ "หัวข้อ" — ยังไม่ใช้จริง

⚠️ ไฟล์นี้ยังไม่ถูก import จาก production เลย ตั้งใจให้แยกจนกว่าจะวัดผลผ่านครบ
(memory.build_summary_prompt เดิมยังทำงานอยู่ ไม่ถูกแตะ)

ปัญหาที่แก้: summary ปัจจุบันบอกแค่หัวข้อ
    "23 ก.ค.: คุยเรื่องความแตกต่างระหว่างเจลาโต้และไอศกรีม"
ผู้ใช้ถาม "ผมชอบของหวานอะไร" → ตอบไม่ได้ เพราะ summary ไม่ได้เก็บว่าชอบอะไร

ต้นเหตุอยู่ที่ memory.build_summary_prompt ที่สั่งไว้ว่า "ห้ามเติมรายละเอียด" +
"สั้นที่สุดเท่าที่จะบอกหัวข้อได้" บวก verify pass ที่ตามลบรายละเอียดอีกชั้น — กฎนี้เขียน
กัน hallucinate ซึ่งถูกต้อง แต่เหวี่ยงเกิน: ห้ามทั้งของแต่งขึ้นและของที่ผู้ใช้พูดจริง

แนวคิด: เปลี่ยนจาก "ห้ามใส่รายละเอียด" → "ใส่ได้ ถ้ายกมาจากบทจริง" แล้วตรวจความจริงด้วย
rule (ตรวจได้แน่นอน) แทนการถามโมเดลว่าตัวเองแต่งไหม (ซึ่งตอบผิดได้)
— หลักการเดียวกับ llm_tools._strip_ungrounded_optional_args ที่ใช้แก้ปัญหาโมเดลเดา province

ผลวัดขั้นที่ 1 (บทแต่งเอง 3 เคส × 5 รอบ):
    ปัจจุบัน  เก็บเนื้อหา  83%   ยาว 45c
    v2        เก็บเนื้อหา 100%   ยาว 82c
    hallucinate = 0 ทั้งคู่ (grounding ยังไม่เคย trigger เพราะโมเดลไม่แต่งเลยในเคสนั้น)
"""
import re

# ── ประโยคที่รอสเต้ "บรรยายตัวเอง" — ไม่ควรเก็บเป็นความทรงจำ ────────────────────
#
# ⚠️ ไม่ใช่ว่ารอสเต้ห้ามมีความชอบ — persona.py:44-51 บอกชัดว่าเธอ *ต้อง* มีความรู้สึกและ
# ความเห็นของตัวเอง ("ชอบอะไร ก็กล้าตอบว่าชอบ") นั่นคือคาแร็กเตอร์ ไม่ใช่บั๊ก
#
# ปัญหาอยู่ที่การ *เก็บ* มันเป็น summary ต่างหาก เพราะความชอบพวกนี้โมเดลเสกสดทุกครั้ง
# ไม่ได้มาจาก persona ตายตัว — วัดแล้วเจอ 2 แบบจากบทจริง:
#     "รอสเต้ตอบว่าเธอชื่อรอสเต้ เป็นเด็กสาวชอบอ่านหนังสือ และเขียนบันทึกในสมุดเก่า"
#     "ส่วนตัวชอบเวอร์ชันเพลงที่มีเสียงเปียโนเบาๆ คลออยู่"
# ("เขียนบันทึกในสมุดเก่า" ไม่มีใน persona.py เลย = แต่งสดๆ)
#
# พอเก็บลง summary แล้ว recall กลับมา มันกลายเป็น "ข้อเท็จจริง" ที่รอสเต้ยึดถือแล้วต่อยอด
# → ความทรงจำปลอมที่สะสมเพี้ยนขึ้นเรื่อยๆ ทั้งที่ตอนพูดเป็นแค่การคุยเล่นครั้งเดียว
#
# จับ 2 ฝั่งประกบกัน (ประธาน + กริยาบรรยายตัวตน) ไม่ใช่ keyword เดี่ยว — กันจับผิดเวลา
# summary เล่าว่ารอสเต้ *ทำอะไรให้ผู้ใช้* ซึ่งต้องเก็บไว้ ("รอสเต้แนะนำร้านก๋วยเตี๋ยว")
_SELF_SUBJECT = r"(?:รอสเต้|เธอ|ตัวเอง|ส่วนตัว)"
_SELF_DESC_RE = re.compile(
    # "รอสเต้ชอบ..." / "ส่วนตัวชอบ..." / "เธอชื่อรอสเต้"
    rf"{_SELF_SUBJECT}\s*(?:ก็|นั้น|เอง)?\s*"
    r"(?:ชอบ|ไม่ชอบ|สนใจ|ชื่อ|เป็นเด็ก|เป็นคน|มีนิสัย|รู้สึก|อยาก|ฝัน|เคยเป็น)",
)
# รูปที่ประธานถูกละไว้แต่เป็นการเล่าตัวตนชัดเจน ("เป็นเด็กสาวชอบอ่านหนังสือ")
_SELF_DESC_BARE_RE = re.compile(
    r"เป็นเด็กสาว|ดูแลห้องสมุด|ผู้ดูแลห้องสมุด|แม่มด"
)


# ผู้ใช้ถามถึงตัวรอสเต้เอง — ถ้าเจอในบท การที่ summary พูดถึงรอสเต้ก็ *ถูกต้อง* ไม่ใช่การหลุด
#
# ทำไมต้องดูบทด้วย ไม่ใช่ดูแค่ summary: วัดแล้วเจอว่า detector ที่ดูแค่ summary จับผิด 6/10
# ครั้ง เพราะบทจริงก้อนหนึ่งเริ่มด้วย "รอสเต้ชอบอ่านนิยายแบบไหนเหรอ" — คำถามนี้ถามรสนิยม
# ของรอสเต้ตรงๆ summary ที่ถูกต้องของบทนั้นจึง *ต้อง* พูดถึงสิ่งที่รอสเต้ชอบ ไม่มีทางเลี่ยง
# การสั่งห้ามจึงเป็นคำสั่งที่ทำตามไม่ได้ (และ retry ก็แก้ไม่ได้ — วัดแล้วหายแค่ 1/6)
_USER_ASKS_ABOUT_ROSTE_RE = re.compile(
    r"(?:รอสเต้|เธอ|น้อง)\s*(?:ชอบ|ไม่ชอบ|สนใจ|เป็นใคร|ชื่ออะไร|ทำอะไร|อยาก|รู้สึก|คิดว่า)"
    r"|แนะนำตัว|เล่าเรื่องตัวเอง|เกี่ยวกับตัวเธอ"
)


def user_asked_about_roste(pairs: list) -> bool:
    """ผู้ใช้ถามถึงตัวรอสเต้เองในบทนี้ไหม — ดูเฉพาะข้อความฝั่งผู้ใช้

    ต้องดูเฉพาะฝั่ง user เท่านั้น ถ้าดูทั้งบทจะเจอคำว่า "รอสเต้ชอบ" ในคำตอบของบอทเองแล้ว
    อนุญาตทุกครั้ง กลายเป็นไม่ได้กรองอะไรเลย
    """
    for m in pairs:
        if m.get("role") == "user" and _USER_ASKS_ABOUT_ROSTE_RE.search(m.get("content") or ""):
            return True
    return False


def find_self_description(summary: str, pairs: list | None = None) -> list:
    """คืนส่วนของ summary ที่เป็น "รอสเต้บรรยายตัวเองโดยไม่มีใครถาม" — ควรขอสรุปใหม่

    คืน [] ถ้าไม่เจอ (= summary นี้เก็บได้)

    pairs: บทสนทนาต้นทาง — ถ้าผู้ใช้ถามถึงตัวรอสเต้ในบทนี้ จะไม่ flag เลย เพราะการที่
    summary เก็บคำตอบนั้นไว้ *ถูกต้องแล้ว* (ผู้ใช้อาจถามย้อนหลังว่า "รอสเต้ชอบอะไรนะ")
    ส่งเป็น None = ตรวจแบบไม่ดูบริบท (ใช้ตอนเทสตัว regex ตรงๆ)

    ⚠️ ต้องไม่จับ "สิ่งที่รอสเต้ทำให้ผู้ใช้" ซึ่งเป็นประวัติร่วมกันจริงที่มีค่า —
    "รอสเต้แนะนำร้านก๋วยเตี๋ยว" / "รอสเต้ตอบราคาน้ำมัน" ต้องผ่านเสมอ
    """
    if pairs is not None and user_asked_about_roste(pairs):
        return []
    hits = []
    for m in _SELF_DESC_RE.finditer(summary):
        hits.append(summary[m.start():m.start() + 34].strip())
    for m in _SELF_DESC_BARE_RE.finditer(summary):
        hits.append(summary[m.start():m.start() + 34].strip())
    return hits


def build_summary_prompt_v2(pairs: list) -> str:
    """prompt ที่ขอทั้งหัวข้อ *และ* เนื้อหาจริงของบทสนทนา (ทั้งฝั่งผู้ใช้และสิ่งที่รอสเต้ทำให้)

    ต่างจาก memory.build_summary_prompt ตรงที่ไม่ห้ามรายละเอียด แต่บังคับให้ใช้คำเดียวกับ
    ในบท (ทำให้ grounding check ตรวจได้) และยังห้ามชื่อเฉพาะ/ตัวเลขที่ไม่มีในบทเหมือนเดิม

    ⚠️ เคยลองใส่กฎ "ห้ามเก็บคำที่รอสเต้บรรยายตัวเอง" ลงใน prompt แล้ว **ไม่ได้ผล** —
    วัดกับบทจริงแล้วโมเดลยังหลุด และหลุดในรูปที่แย่กว่าเดิมด้วย ("ส่วนตัวชอบเวอร์ชันเพลง
    ที่มีเสียงเปียโนเบาๆ") จึงถอดกฎนั้นออกแล้วย้ายไปเป็น rule ตรวจหลังบ้าน
    (find_self_description) แทน — ตรงกับบทเรียนที่เจอซ้ำแล้วในโปรเจกต์นี้ว่า prompt
    แก้พฤติกรรมโมเดลไม่ได้ ต้องมี validation layer (ดู _strip_ungrounded_optional_args
    และ fix_persona_slips ที่เจอปัญหาเดียวกันมาก่อน)

    *สิ่งที่รอสเต้ทำให้ผู้ใช้* (แนะนำร้าน ตอบคำถาม ให้ข้อมูล) ยังเก็บไว้ เพราะเป็น
    ประวัติร่วมกันจริงที่มีค่าตอนผู้ใช้ถามย้อนหลัง ("เคยแนะนำร้านอะไรไว้")
    """
    convo = "\n".join(
        f"{'ผู้ใช้' if m['role'] == 'user' else 'รอสเต้'}: {m.get('content', '')}"
        for m in pairs
    )
    return (
        "สรุปบทสนทนาต่อไปนี้เป็นภาษาไทย 1 บรรทัด โดยเก็บ *เนื้อหาที่คุยกันจริง* ไว้ด้วย\n"
        "กฎ:\n"
        "- เขียนทั้งหัวข้อที่คุย และสิ่งที่ผู้ใช้ชอบ/ไม่ชอบ/ทำ/ตัดสินใจ ถ้ามีในบท\n"
        "- สิ่งที่รอสเต้ทำให้ผู้ใช้ (แนะนำอะไร ตอบข้อมูลอะไร) เก็บไว้ได้\n"
        "- ใช้คำเดียวกับที่ปรากฏในบทสนทนา ห้ามเปลี่ยนเป็นคำอื่นที่ความหมายใกล้เคียง\n"
        "- ห้ามเติมชื่อเฉพาะ/ตัวเลข/รายละเอียดที่ไม่ได้อยู่ในบทข้างล่าง\n"
        "- ไม่เกิน 2 ประโยค เขียนติดกันเป็นบรรทัดเดียว\n"
        "ตอบมาแค่ประโยคสรุปเท่านั้น ห้ามมีคำนำ:\n\n"
        + convo
    )


def _conversation_text(pairs: list) -> str:
    return " ".join((m.get("content") or "") for m in pairs)


def find_ungrounded(summary: str, pairs: list) -> list:
    """คืน "ข้อเท็จจริงเฉพาะเจาะจงที่ไม่ปรากฏในบท" = สัญญาณว่าโมเดลแต่งขึ้น

    ⚠️ ตรวจอย่างเดียว ไม่แก้สตริง — ทดสอบแล้วพบว่าการ "ตัดคำที่ไม่มีในบททิ้ง" พัง 2 แบบ:
      1. ตัดกลางประโยคได้เศษคำ: "เจลาโต้รสช็อกโกแลตที่ร้านสเวนเซ่นส์" → "เจลาโต้รสส"
      2. สรุปที่ถูกต้องถูกลบจนหมด: "คุยเรื่องของหวาน" → ""
    เจอแล้วจึงควร "ขอสรุปใหม่" (fail-conservative) ไม่ใช่ซ่อมสตริงที่โมเดลเขียน

    ⚠️ ตรวจเฉพาะคำนามเฉพาะ/ตัวเลข ไม่ใช่ทุกคำที่ไม่อยู่ในบท เพราะการสรุปคือการสรุปความ
    โดยธรรมชาติ — บทที่คุยเรื่องเจลาโต้กับไอศกรีม สรุปว่า "ของหวาน"/"ความแตกต่าง" ได้ถูกต้อง
    ทั้งที่คำนั้นไม่อยู่ในบทตรงๆ (ทดสอบแล้วว่าการเช็คทุกคำ flag สองอันนี้ผิด = false positive)

    ข้อจำกัดที่รู้แล้ว: ชื่อเฉพาะภาษาไทยที่ไม่มีเครื่องหมายคำพูดกำกับ ตรวจไม่เจอ
    ("เจลาโต้ที่ร้านสเวนเซ่นส์") — จึงยังต้องคง verify pass ของโมเดลไว้เป็นชั้นสอง
    """
    convo = _conversation_text(pairs)
    out = []

    # ตัวเลขที่ไม่มีในบท — โมเดลชอบเติมราคา/จำนวน/ปีเอง
    for num in re.findall(r"\d+(?:[.,]\d+)?", summary):
        if num not in convo:
            out.append(num)

    # คำในเครื่องหมายคำพูด = โมเดลกำลังอ้างชื่อเฉพาะ
    for quoted in re.findall(r"[\"'“”‘’]([^\"'“”‘’]{2,40})[\"'“”‘’]", summary):
        q = quoted.strip()
        if q and q not in convo:
            out.append(q)

    # คำภาษาอังกฤษ (ชื่อยี่ห้อ/ชื่อเฉพาะมักเขียนด้วยอักษรละติน)
    for eng in re.findall(r"[A-Za-z][A-Za-z0-9]{2,}", summary):
        if eng.lower() not in convo.lower():
            out.append(eng)

    return out


def clip_summary(summary: str, max_chars: int = 160) -> str:
    """กัน summary ยาวเกินคุม — ตัดที่ขอบประโยค/วรรคที่ใกล้ที่สุด ไม่ตัดกลางคำ

    ทำไมต้องมี: ขนาดที่เข้า context มีราคาจริง (วัดได้ว่า >3,700c ทำให้โมเดลลืม summary)
    v2 ยาวเฉลี่ย 82c ซึ่งยังปลอดภัย แต่ไม่มีอะไรกันไม่ให้โมเดลเขียนยาว 300c ในบทที่ซับซ้อน
    เพดานนี้จึงเป็นตัวกันขอบ ไม่ใช่ตัวบีบ (ปกติไม่ควรถูก trigger)
    """
    s = summary.strip()
    if len(s) <= max_chars:
        return s
    cut = s[:max_chars]
    for sep in ("။", "। ", ". ", " แล้ว", " และ", " แต่", " "):
        pos = cut.rfind(sep)
        if pos > max_chars * 0.5:
            return cut[:pos].strip()
    return cut.strip()
