def hr(w=78):
    print("─" * w)


async def main():
    mem_path = os.path.join(memory.MEMORY_DIR, f"{TEST_USER_ID}.json")
    if os.path.exists(mem_path):
        os.remove(mem_path)

    idx = 0
    for group, turns in CASES:
        idx += 1
        # multi-turn เคสเดียวกันต้องรีเซ็ต memory ก่อนเริ่ม กันบทสนทนาเก่าปนข้ามเคส
        if os.path.exists(mem_path):
            os.remove(mem_path)
        hr()
        print(f"[{idx:02d}] กลุ่ม: {group}")
        for t_i, turn_msg in enumerate(turns, 1):
            # จำลอง bot.py:on_message จริง — เช็ค "คำสั่งความจำ" (จำไว้ว่า.../ลืมเรื่อง...) ก่อน
            # เรียกโมเดลเสมอ เจอจริง: ข้าม path นี้ไปทำให้ "จำไว้ว่าฉันชื่อปอนด์" ไหลเข้าโมเดลตรงๆ
            # เหมือนข้อความธรรมดา แล้วโมเดลเดางงจนหลุด AI-identity — ไม่ใช่บั๊ก production จริง
            # แค่สคริปต์ทดสอบเดิมข้าม mechanism ที่มีอยู่แล้วไป
            mem_reply = memory.handle_memory_command(TEST_USER_ID, "ผู้ทดสอบ", turn_msg)
            prefix = f"  เทิร์น{t_i}" if len(turns) > 1 else "  ผู้ใช้"
            print(f"{prefix}: {turn_msg!r}")
            if mem_reply is not None:
                print(f"  🤖: {mem_reply}  [ตอบผ่านคำสั่งความจำ ไม่เรียกโมเดล]")
                continue
            reply = await chat.ask_ollama(TEST_USER_ID, "ผู้ทดสอบ", turn_msg)
            print(f"  🤖: {reply}")
        print()

    if os.path.exists(mem_path):
        os.remove(mem_path)
    hr()
    print(f"จบทั้งหมด {idx} เคส")


if __name__ == "__main__":
    asyncio.run(main())
