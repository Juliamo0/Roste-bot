def install(user_id: int) -> None:
    """เขียน fixture ลงไฟล์ความจำของ user id ทดสอบ (ทับของเดิม)"""
    import memory
    mem = {
        "name": "ผู้ทดสอบ",
        "preferred_name": "",
        "facts": [dict(f, created="2026-07-26T00:00:00+07:00", superseded=False,
                       superseded_at=None, superseded_by=None) for f in FACTS],
        "history": [],
        "summaries": [{"date": "2026-08-01", "text": s} for s in SUMMARIES],
    }
    memory.save_memory(user_id, mem)


def uninstall(user_id: int) -> None:
    import os
    import memory
    p = memory._memory_path(user_id)
    if os.path.exists(p):
        os.remove(p)
