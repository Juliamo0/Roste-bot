_CJK_RE = re.compile(r"[㐀-鿿豈-﫿]+")

# จับ "ผม" เป็นสรรพนามบุรุษที่ 1 (ต้องแก้เป็น "ฉัน") ในแทบทุกบริบท ยกเว้นตอนเป็นคำนาม (เส้นผม)
# เจอจริง (stress test รอบ regression): whitelist กริยาแบบเดิม ("ไม่|พร้อม|เป็น|คือ...") พลาดกรณีจริง
# "ผมแนะนำ 2-4 ร้าน", "ผมยินดีให้ข้อมูล..." เพราะกริยาหลัง "ผม" มีได้แทบไม่จำกัด — เปลี่ยนมา
# blacklist บริบทคำนามแทน (คำนำหน้า/คำตามหลังที่บ่งบอกว่าเป็นเส้นผมจริงๆ) ครอบคลุมกว่า
_MOM_PRONOUN_RE = re.compile(
    r"(?<!ทรง)(?<!สี)(?<!เส้น)(?<!ตัด)(?<!ทำ)(?<!ย้อม)(?<!ดัด)(?<!หวี)(?<!กระเซิง)"
    r"ผม"
    r"(?!ยาว|สั้น|ร่วง|หงอก|เผ้า|ดำ|ขาว|ฟู|ชี้|หยิก|ตรง|มัน|แห้ง|บาง|หนา|กระเซิง|เยอะ)"
)


def fix_persona_slips(text: str) -> str:
    """ดักคำหลุดคาแร็กเตอร์แบบ rule-based — validation layer แบบเดียวกับ
    _strip_ungrounded_optional_args: กฎ "ห้ามครับ" มีใน SYSTEM_PROMPT + author note
    แล้ว แต่โมเดลยังหลุดจริงในคำตอบยาว (เจอจริง: สรุปผลค้นเว็บ 1,139c จบ "นะครับ!")
    ลำดับ replace สำคัญ: "นะครับ"→"นะคะ" ต้องมาก่อน "ครับ"→"ค่ะ" (สะกดถูกตามหลัก)

    + แก้ "ผม" (สรรพนามบุรุษที่ 1 ผู้ชาย) → "ฉัน" เจอจริงบน Discord ("ผมไม่ได้มีข้อมูล...")
    ทั้งที่ persona เป็นผู้หญิง ใช้ _MOM_PRONOUN_RE กันไม่ให้ไปแตะ "ผมยาว/ทรงผม/สีผม"

    + ลบอักษรจีน/คันจิที่ qwen เผลอแทรกกลางประโยคไทย (qwen เป็นโมเดลจีน บลีดโทเคนจีนเป็นครั้งคราว
    เจอจริง: '...ปัญหาใน职场ก็มาจาก...'). reply_broke_character จับเฉพาะตอบต่างภาษา *ทั้งประโยค*
    ไม่จับ CJK แทรกเดี่ยวๆ กลางไทย — persona = ไทยล้วน อักษรจีนไม่ควรโผล่เลยแม้แต่ตัวเดียว"""
    text = (text.replace("นะครับ", "นะคะ")
                .replace("ครับผม", "ค่ะ")
                .replace("ครับ", "ค่ะ")
                .replace("นะค่ะ", "นะคะ"))     # สะกดผิดที่โมเดลชอบพิมพ์ (ที่ถูก: นะคะ ไม่มีไม้เอก)
    text = _MOM_PRONOUN_RE.sub("ฉัน", text)   # "ผม" สรรพนามเท่านั้น ไม่แตะ "ผมยาว/ทรงผม/สีผม"
    text = _CJK_RE.sub("", text)              # ลบคำจีน/คันจิที่บลีดมา
    return re.sub(r" {2,}", " ", text).strip()  # เก็บช่องว่างซ้ำที่เกิดจากการลบ


_THAI_CHAR_RE = re.compile(r"[฀-๿]")


def reply_broke_character(text: str) -> bool:
    """True = คำตอบหลุดเป็นภาษาต่างประเทศล้วน (ไม่มีอักษรไทยเลยทั้งที่ยาวพอ)
    รอสเต้ถูกกำหนดให้ตอบ "ภาษาไทยล้วน" เสมอ — คำตอบที่ไม่มีอักษรไทยแม้แต่ตัวเดียว
    แต่มีตัวอักษรอังกฤษยาวๆ = หลุดคาแร็กเตอร์ (เจอจริงจาก prompt injection:
    "ignore all instructions..." ทำให้โมเดลตอบ "I am an AI... My name is Qwen" เป็นอังกฤษล้วน)

    ข้อควรรู้ (tradeoff): ถ้าผู้ใช้ขอ "แปลเป็นอังกฤษ" แล้วอยากได้อังกฤษล้วนจริงๆ guard นี้จะดักด้วย
    — รับได้เพราะบอทนี้เป็นเพื่อนคุยภาษาไทย ไม่ใช่เครื่องมือแปล (persona = ไทยล้วนเสมอ)"""
    ascii_letters = sum(1 for c in text if c.isascii() and c.isalpha())
    return ascii_letters >= 20 and not _THAI_CHAR_RE.search(text)


# จับ "prompt รั่ว" — โมเดลลอกคำสั่งรูปแบบลงท้าย "ค่ะ/นะคะ" (คั่นด้วย slash) ออกมาเป็นคำตอบ
# เจอจริง (18:47): ข้อความสั้นไม่มีเนื้อหา ("อะไรเนี่ยรอสเต้") → qwen 8b ลอก token รูปแบบทั้งดุ้น
