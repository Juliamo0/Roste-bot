_PERSONA_LEAK_RE = re.compile(r"ค่ะ\s*/\s*นะคะ")


def reply_is_persona_leak(text: str) -> bool:
    """True = คำตอบเป็นการลอกคำสั่งรูปแบบ persona ("ค่ะ/นะคะ" คั่นด้วย slash) ออกมาตรงๆ
    แทนที่จะตอบจริง — โมเดลเล็กชอบทำตอนเจอข้อความสั้นที่ไม่รู้จะตอบอะไร ผู้เรียก (ask_ollama)
    เจอ True แล้วแทนด้วย fallback — กฎ+การถอด slash ใน prompt กันชั้นแรก อันนี้เป็น safety net"""
    return bool(_PERSONA_LEAK_RE.search(text))


