    # การปฏิเสธ/ห้าม (เชิงลบ) นี่จับการ "ประกาศเจตนา" ตรงๆ (เชิงบวก) รวมถึงชื่อฟังก์ชัน tool จริง
    # ที่หลุดออกมา (get_weather, get_oil_price, ฯลฯ) ซึ่งไม่ควรปรากฏในคำตอบที่ผู้ใช้เห็นเด็ดขาด
    r"ควร(?:ใช้|เรียกใช้)เครื่องมือ|เราควรเรียก|"
